#!/usr/bin/env python3
"""Convert the X11 misc-fixed 5x7 font (figlet's 5x7.flf, converted from 5x7.bdf)
into the Go glyph table of pkg/cv/text (glyphs_5x7.go).

usage: 01-flf-to-go-glyphs.py /opt/homebrew/.../figlet/fonts/5x7.flf > pkg/cv/text/glyphs_5x7.go
"""
import sys

WANT = [chr(c) for c in range(32, 127)] + ["×"]  # printable ASCII and the multiplication sign

def load(path):
    lines = open(path, encoding="latin-1").read().split("\n")
    head = lines[0].split()
    height, ncomment = int(head[1]), int(head[5])
    i = 1 + ncomment
    glyphs = {}
    def take(i):
        rows = [l.rstrip("@").replace("$", " ") for l in lines[i:i + height]]
        return rows, i + height
    for code in list(range(32, 127)) + [196, 214, 220, 228, 246, 252, 223]:
        rows, i = take(i)
        glyphs[chr(code)] = rows
    while i < len(lines) and lines[i].strip():
        tag = lines[i].split()[0]
        code = int(tag, 0)
        rows, i = take(i + 1)
        glyphs[chr(code)] = rows
    return glyphs

def bits(row):
    v = 0
    for k, ch in enumerate(row.ljust(5)[:5]):
        if ch != " ":
            v |= 1 << (4 - k)
    return v

def main():
    g = load(sys.argv[1])
    print("// Code generated by GCV-002 scripts/01-flf-to-go-glyphs.py; DO NOT EDIT.")
    print()
    print("// Glyphs of the X11 misc-fixed 5x7 font (5x7.bdf, Copyright 1991 X Consortium, X11 license),")
    print("// read from figlet's 5x7.flf conversion of it.")
    print()
    print("package text")
    print()
    print("// misc5x7 holds one glyph per rune: 7 rows of 5 bits, most significant bit on the left.")
    print("var misc5x7 = map[rune][glyphH]uint8{")
    for ch in WANT:
        rows = g[ch]
        vals = ", ".join("0x%02X" % bits(r) for r in rows)
        name = repr(ch) if ch not in "\\'" else ("'\\\\'" if ch == "\\" else "'\\''")
        if ch == "×":
            name = "'×'"
        print("\t%s: {%s}," % (name, vals))
    print("}")

if __name__ == "__main__":
    main()
